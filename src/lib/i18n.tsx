interface I18nValue {
  lang: Language
  setLang: (lang: Language) => void
  toggleLang: () => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const stored = localStorage.getItem('kadc_lang')
    return stored === 'en' ? 'en' : 'bn'
  })

  useEffect(() => {
    document.documentElement.lang = lang
    localStorage.setItem('kadc_lang', lang)
  }, [lang])

  const setLang = useCallback((next: Language) => setLangState(next), [])
  const toggleLang = useCallback(() => setLangState((value) => (value === 'bn' ? 'en' : 'bn')), [])
  const t = useCallback((key: string) => dictionary[key]?.[lang] || dictionary[key]?.bn || key, [lang])

  const value = useMemo(() => ({ lang, setLang, toggleLang, t }), [lang, setLang, toggleLang, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}

export function pickBilingual(
  source: Record<string, unknown>,
  base: string,
  lang: Language,
): string {
  const preferred = source[`${base}${lang === 'bn' ? 'Bn' : 'En'}`]
  const fallback = source[`${base}Bn`]
  return String(preferred || fallback || '')
}
